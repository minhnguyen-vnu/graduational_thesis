#!/usr/bin/env python3
"""
Build the single OpenAPI document EvoMaster fuzzes for Tier-2b.

pyLoad exposes two surfaces and documents only one of them:

  /api/*   84 paths, RPC-style  -- specification GENERATED BY pyLOAD ITSELF, fetched from
                                   GET /api/openapi.json (admin-only), saved as
                                   openapi-api-generated.json. Not written by us.
  /json/*  20 paths, web UI     -- undocumented; openapi-json-routes.json is hand-written from
                                   the blueprint source, all 20 routes, cross-checked both ways.

EvoMaster takes one --bbSwaggerUrl, so the two are merged here rather than edited into each other.
Keeping the generated half untouched and in its own file is the point: most of the fuzzed surface
is described by the application, not by us, and anyone can re-fetch it to check.

The hand-written half is OpenAPI 3.0 and the generated half is 3.1.1, so `nullable: true` is
rewritten to the 3.1 type-array form on the way in; nothing else is altered.
"""
import json
import pathlib

HERE = pathlib.Path(__file__).parent


def to_31(node):
    """Rewrite 3.0 `nullable: true` into 3.1 `type: [t, "null"]`, recursively."""
    if isinstance(node, dict):
        node = {k: to_31(v) for k, v in node.items()}
        if node.pop("nullable", False) and "type" in node:
            t = node["type"]
            node["type"] = ([t, "null"] if isinstance(t, str) else list(t) + ["null"])
        return node
    if isinstance(node, list):
        return [to_31(x) for x in node]
    return node


def main():
    api = json.loads((HERE / "openapi-api-generated.json").read_text())
    web = to_31(json.loads((HERE / "openapi-json-routes.json").read_text()))

    overlap = set(api["paths"]) & set(web["paths"])
    if overlap:
        raise SystemExit(f"paths collide between the two surfaces: {sorted(overlap)}")

    merged = dict(api)
    merged["info"] = {
        "title": "pyLoad (merged: generated /api + hand-written /json)",
        "version": api.get("info", {}).get("version", "0.5.0b3.dev97"),
        "description": (
            "Merged by merge_specs.py. The /api/* half is pyLoad's own generated specification, "
            "unmodified. The /json/* half is hand-written from json_blueprint.py because pyLoad "
            "does not document that surface; all 20 of its routes are included, not only the ones "
            "the MR-A1 triple needs. See docs/tier2b-pyload-target.md §3."
        ),
    }
    merged["paths"] = {**api["paths"], **web["paths"]}
    merged.setdefault("components", {}).setdefault("securitySchemes", {}).update(
        web.get("components", {}).get("securitySchemes", {})
    )

    out = HERE / "openapi-merged.json"
    out.write_text(json.dumps(merged, indent=1))
    ops = sum(len([m for m in v if m.lower() in
                   ("get", "put", "post", "delete", "patch", "head", "options")])
              for v in merged["paths"].values())
    print(f"/api paths: {len(api['paths'])}  /json paths: {len(web['paths'])}"
          f"  merged paths: {len(merged['paths'])}  operations: {ops}")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
